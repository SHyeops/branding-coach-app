def flat_options(sc):
    """장면 3처럼 소제목으로 나뉜 보기도 한 줄 목록으로"""
    opts = sc.get("options", [])
    return [o for _, group in opts for o in group] if opts and isinstance(opts[0][1], list) else opts


def brand_type(kind, picks):
    """picks[i] = 장면 i에서 고른 보기 문구 목록 → (유형, {유형: [근거 보기]})"""
    reasons = {t: [] for t in TYPES}
    for sc, chosen in zip(SCENES[kind], picks):
        kinds = dict(flat_options(sc))
        for text in chosen:
            if kinds.get(text):
                reasons[kinds[text]].append(text)
    first = dict(flat_options(SCENES[kind][0])).get((picks[0] or [None])[0])
    best = max(TYPES, key=lambda t: (len(reasons[t]), t == first))
    return best, reasons


